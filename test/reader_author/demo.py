#!/usr/bin/env python3
"""Generate and check the stranger's native-language demo from real commands."""
import argparse
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import uuid

from route import ROOT, Replay, dump, require, sha

FIXTURE = ROOT / 'test/reader_author/fixtures/demo/expectations.json'
EDIT = "from pathlib import Path; p = Path('reader.lang'); s = p.read_text(); old = 'name:symbol value:parcel_value'; assert s.count(old) == 1; p.write_text(s.replace(old, \"name:symbol '='? value:parcel_value\"))"
POLICY = "from pathlib import Path; Path('policy.parcel').write_text('parcel { base = 10; free_over = 100; }\\n')"
FILES = "from pathlib import Path; print('\\n'.join(str(p) for p in sorted(Path('editor').iterdir())))"


def check_output(name, result, expectation, normalize):
    require(result.returncode == expectation['exit'], name + ': unexpected exit code')
    for stream in ('stdout', 'stderr'):
        actual = normalize(getattr(result, stream).decode())
        require(actual == expectation[stream], name + ': unexpected ' + stream + ': ' + repr(actual))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--case', choices=['stranger'], required=True)
    parser.add_argument('--evidence', type=Path)
    parser.add_argument('--update', action='store_true', help='write docs/DEMO.md after checking command expectations')
    args = parser.parse_args()
    os.nice(10)
    os.sched_setaffinity(0, sorted(os.sched_getaffinity(0))[:2])
    token = uuid.uuid4().hex
    evidence = (args.evidence or ROOT.parent / 'evidence' / ('demo-' + token)).resolve()
    require(evidence != ROOT and ROOT not in evidence.parents, 'evidence must be outside checkout')
    evidence.mkdir(parents=True, exist_ok=False)
    scratch = ROOT.parent / 'scratch' / ('demo-' + token)
    scratch.mkdir(parents=True)
    replay = Replay(evidence, scratch)
    replay.env.update(MAKEFLAGS='-j2', PYTHONDONTWRITEBYTECODE='1')
    for key in ('LANG_ROOT', 'LANG_CLANG', 'LANG_NATIVE_TRACE', 'LANG_INSPECT_STAGE', 'VERIFY_CASE'):
        replay.env.pop(key, None)
    print('evidence:', evidence, flush=True)
    try:
        replay.run(['make', 'build'], 'build-current-sources', ROOT)
        compiler = str(ROOT / 'out/lang_next')
        work = scratch / 'stranger demo'
        work.mkdir()
        require(' ' in str(work), 'demo must exercise a path with a space')
        project = work / 'parcel'
        def normalize(text):
            text = re.sub(r'policy\.lang-build-[A-Za-z0-9]{6}/', 'policy.lang-build-<temp>/', text)
            text = text.replace('toolchain=' + shutil.which('clang'), 'toolchain=clang')
            return text.replace(str(Path(compiler).resolve()), 'lang').replace(
                compiler, 'lang').replace(str(scratch), '<workspace>')
        expectations = json.loads(FIXTURE.read_text())
        steps = [
            ('new', [compiler, 'new', 'language', 'parcel'], work),
            ('grammar-edit', ['python3', '-c', EDIT], project),
            ('policy-edit', ['python3', '-c', POLICY], project),
            ('build', [compiler, 'build', '--project', 'project.lang-project', 'policy.parcel', '-o', 'policy'], project),
            ('native-99', ['./policy', '99'], project),
            ('native-100', ['./policy', '100'], project),
            ('malformed', [compiler, 'build', '--project', 'project.lang-project', 'syntax.parcel', '-o', 'invalid'], project),
            ('editor', [compiler, 'project', 'editor', 'project.lang-project', '-o', 'editor'], project),
            ('editor-files', ['python3', '-c', FILES], project),
        ]
        require(set(expectations) == {name for name, _, _ in steps}, 'expectation steps differ')
        transcript = ['# Make a language, run a native executable\n\n',
                      'Generated by `python3 -B test/reader_author/demo.py --case stranger`.\n',
                      'Only compiler, temporary workspace and temporary build paths are normalized.\n',
                      'The grammar edit adds optional `=`; the policy uses it. Fees are 10 below 100 and 0 at 100.\n\n',
                      '```console\n']
        cwd = None
        for name, command, directory in steps:
            if cwd != directory:
                transcript.append('$ cd ' + shlex.quote(normalize(str(directory))) + '\n')
                cwd = directory
            transcript.append('$ ' + normalize(shlex.join(command)) + '\n')
            expected = expectations[name]
            result = replay.run(command, name, directory, expected=expected['exit'])
            check_output(name, result, expected, normalize)
            transcript.extend(normalize(stream.decode()) for stream in (result.stdout, result.stderr))
            transcript.append('[exit ' + str(result.returncode) + ']\n')
        transcript.append('```\n')
        document = ''.join(transcript).encode()
        (evidence / 'DEMO.md').write_bytes(document)
        require((project / 'policy').read_bytes()[:4] == b'\x7fELF', 'output must be a native ELF executable')
        require(not (project / 'invalid').exists(), 'malformed input produced an executable')
        require(b'^' in document, 'missing caret diagnostic')
        grammar = json.loads((project / 'editor/parcel.tmLanguage.json').read_text())
        require(any(re.fullmatch(p.get('match', '(?!)'), '=') for p in grammar['patterns']),
                'editor grammar must reflect the one-line grammar edit')
        # Prove both checks reject changed expectations, including under --update.
        probe = subprocess.CompletedProcess([], 0, stdout=b'10\n', stderr=b'')
        rejected = []
        for field, wrong in [('exit', 1), ('stdout', '11\n')]:
            bad = dict(expectations['native-99'], **{field: wrong})
            try:
                check_output('mutation-' + field, probe, bad, normalize)
            except RuntimeError:
                rejected.append(field)
        require(rejected == ['exit', 'stdout'], 'changed expectations did not fail')
        dump(evidence / 'expectation-mutations.json', {'rejected': rejected})
        destination = ROOT / 'docs/DEMO.md'
        if not args.update:
            require(destination.read_bytes() == document, 'docs/DEMO.md differs; inspect evidence, then use --update')
        destination.write_bytes(document)
        dump(evidence / 'result.json', {'pass': True, 'head': subprocess.check_output(
            ['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
            'transcript_sha256': sha(evidence / 'DEMO.md'), 'native_sha256': sha(project / 'policy')})
        print('PASS stranger: fresh spaced path, grammar edit, native output, caret, editor files, exact transcript and expectation mutations')
        return 0
    except Exception as error:
        dump(evidence / 'result.json', {'pass': False, 'error': str(error)})
        print('FAIL:', error, file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
