#!/usr/bin/env python3
"""Generate the version constants shared by compiler build paths."""
import argparse
import json
from write_if_changed import write_if_changed


def write_version(version, backend, os_name, arch, libc, bootstrap):
    constants = dict(LANG_VERSION='0.1.0', LANG_COMMIT=version,
                     LANG_BUILD_BACKEND=backend, LANG_BUILD_OS=os_name,
                     LANG_BUILD_ARCH=arch, LANG_BUILD_LIBC=libc,
                     LANG_BOOTSTRAP_FROM=bootstrap)
    content = '// Auto-generated by Makefile - do not edit manually\n'
    content += ''.join(f'var {key} *u8 = {json.dumps(value)};\n'
                       for key, value in constants.items())
    write_if_changed('out/version_info.lang', content.encode())


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ['version', 'backend', 'os', 'arch', 'libc', 'bootstrap']:
        parser.add_argument('--' + name, required=True)
    args = parser.parse_args()
    write_version(args.version, args.backend, args.os, args.arch, args.libc, args.bootstrap)
